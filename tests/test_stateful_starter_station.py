"""§16.14.t1 c1 — stateful starter station tests.

Pins:
  * Template parses, 336 slots/week, persist=true, 24/14 cursor math.
  * Slot strategy mix: 309 sequential + 27 prev_ref (jingle every 12
    starting at slot 12 → 336/12 - 1 = 27 prev_ref slots).
  * Synthetic content pool: 336 tracks across 14 artists, exact cycle
    match. Per-track duration variance (`tid % 7` → 7 buckets).
  * Generator output matches the committed XML byte-for-byte (catches
    drift between `scripts/generate_stateful_starter_pools.py` and
    the committed file).
  * End-to-end generation succeeds for week 1 + week 2; persistent
    cursor advances 24 between weeks (visible: week 1 slot 0's track
    is at week 2 slot ~308, accounting for prev_ref slots).
  * Committed sidecar is valid against the template and matches what
    `derive_sidecar` would produce (drift detection at the sidecar
    layer).
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest


REPO_ROOT = Path(__file__).resolve().parent.parent
STATEFUL_JSON = REPO_ROOT / "stations" / "stateful-starter.json"
STATEFUL_CONTENT_XML = (
    REPO_ROOT / "stations" / "stateful-starter-content.itunes.xml"
)
STATEFUL_SIDECAR = REPO_ROOT / "stations" / "stateful-starter.editor.json"


# ---------- template ----------


def test_template_parses_with_336_slots_and_persist_true() -> None:
    """The template parses cleanly; locked-decision pins (336 slots,
    persist=true, 24 advance, 14 cycle) survive any future edit."""
    from engine.template import parse_template

    raw = json.loads(STATEFUL_JSON.read_text())
    tmpl = parse_template(raw)
    assert tmpl.station == "stateful-starter"
    assert tmpl.slots_per_week() == 336
    assert tmpl.cursor.persist is True
    assert tmpl.cursor.base_advance_per_week == 24
    assert tmpl.cursor.cycle_weeks == 14


def test_template_strategy_mix_matches_design() -> None:
    """D1 lock: sequential (most slots) + prev_ref (sprinkled every
    12 starting at slot 12). 27 prev_ref slots + 309 sequential =
    336 total. If a future edit changes the strategy mix without
    updating the design pass + DESIGN entry, this test fires."""
    raw = json.loads(STATEFUL_JSON.read_text())
    slots = raw["layout"]["flat_slots"]
    assert len(slots) == 336
    sequential = [s for s in slots if s["strategy"] == "sequential"]
    prev_ref = [s for s in slots if s["strategy"] == "prev_ref"]
    assert len(sequential) == 309
    assert len(prev_ref) == 27
    # prev_ref slots land at positions 12, 24, ..., 324 (every 12,
    # starting AFTER position 0). The expected set is multiples of
    # 12 in [12, 336) — same shape as the generator code.
    actual_positions = {s["position"] for s in prev_ref}
    expected = set(range(12, 336, 12))
    assert actual_positions == expected


def test_template_sequential_blocks_bind_to_single_cursor() -> None:
    """All sequential slots reference the one declared cursor
    (STATEFUL_1). D2's "one persistent cursor" lock — catches a
    future edit that accidentally introduces a second cursor without
    updating cursors_init."""
    raw = json.loads(STATEFUL_JSON.read_text())
    sequential = [
        s for s in raw["layout"]["flat_slots"]
        if s["strategy"] == "sequential"
    ]
    cursor_ids = {s["cursor_id"] for s in sequential}
    assert cursor_ids == {"STATEFUL_1"}
    # And the cursor is declared in cursors_init.
    assert raw["layout"]["cursors_init"] == {"STATEFUL_1": 0}


# ---------- content pool ----------


def test_content_pool_has_336_tracks_across_14_artists() -> None:
    """D4 lock: 336 tracks (exact cycle match) split across 14
    artists. 24 tracks per artist is aesthetic (matches cycle_weeks),
    not engine-required — but a deviation is significant enough
    that the user's git diff should surface it."""
    import plistlib

    data = plistlib.loads(STATEFUL_CONTENT_XML.read_bytes())
    tracks = data["Tracks"]
    assert len(tracks) == 336
    artists = {t["Artist"] for t in tracks.values()}
    assert len(artists) == 14
    # Even distribution: 24 tracks per artist.
    from collections import Counter
    counts = Counter(t["Artist"] for t in tracks.values())
    assert set(counts.values()) == {24}


def test_content_pool_durations_vary_per_track() -> None:
    """Same `tid % 7` variance pattern as §16.14 starter (c1-review
    🟢-1) — 7 distinct duration buckets keyed off track id."""
    import plistlib

    data = plistlib.loads(STATEFUL_CONTENT_XML.read_bytes())
    durations = {t["Total Time"] for t in data["Tracks"].values()}
    assert len(durations) == 7, (
        f"expected 7 distinct durations (tid % 7 buckets); got "
        f"{sorted(durations)}"
    )


def test_pool_matches_generator_output() -> None:
    """Per D5: the committed XML is deterministically regenerated by
    `scripts/generate_stateful_starter_pools.py`. Drift here means
    either (a) someone hand-edited the XML and it diverged from the
    generator — run `make refresh-stateful-starter-pools` to reset,
    or (b) the generator changed and the committed file is stale —
    run the same Make target. Either way: run the target."""
    from scripts.generate_stateful_starter_pools import build_content_pool

    assert build_content_pool() == STATEFUL_CONTENT_XML.read_bytes(), (
        "stateful-starter-content.itunes.xml diverged from generator "
        "— run `make refresh-stateful-starter-pools`"
    )


# ---------- sidecar ----------


def test_committed_sidecar_validates_against_template() -> None:
    """D8: the committed sidecar parses + validates against the
    committed template. Sidecar drift would surface here."""
    from engine.editor_metadata import parse_sidecar, validate_sidecar

    raw_template = json.loads(STATEFUL_JSON.read_text())
    sidecar = parse_sidecar(STATEFUL_SIDECAR, station_template=raw_template)
    validate_sidecar(sidecar, station_template=raw_template)
    # `derive_sidecar` reports "1 sections, 28 macros" — pin both.
    assert len(sidecar.get("sections", [])) == 1
    # 28 macros: 27 weighted-style runs between prev_ref slots + 1
    # leading run before slot 12.
    assert len(sidecar.get("macros", [])) == 28


def test_sidecar_matches_derive_output() -> None:
    """Regen-match pin (mirrors §16.14 starter's
    `test_starter_committed_sidecar_matches_derive_output`). If you
    edit the template, this test fails until you re-run the derive
    helper + commit the refreshed sidecar."""
    from scripts.derive_sidecar import derive_sidecar

    raw = json.loads(STATEFUL_JSON.read_text())
    derived = (
        json.dumps(derive_sidecar(raw), indent=2, sort_keys=False) + "\n"
    )
    assert derived == STATEFUL_SIDECAR.read_text(), (
        "stateful-starter.editor.json drifted from derive_sidecar — "
        "re-run `python -m scripts.derive_sidecar --station "
        "stations/stateful-starter.json --out "
        "stations/stateful-starter.editor.json` and commit the result."
    )


# ---------- end-to-end generate (persistent cursor) ----------


def test_end_to_end_generate_two_weeks_advances_cursor(tmp_path) -> None:
    """The flagship pin for D2 — generating two consecutive weeks
    against the same DB advances the persistent cursor by 24
    positions. Week 1 slot 0 ≠ week 2 slot 0 (the cursor moved).

    This is the test that fails LOUDLY if the engine's
    persistent-cursor advance machinery breaks; the stateful-starter
    is a more pedagogically clean tripwire than Rebirth Radio's
    9-cursor real station."""
    from sqlalchemy import create_engine
    from sqlalchemy.orm import sessionmaker

    from engine.importer import import_source
    from engine.models import Base
    from engine.persistence import generate_chain
    from engine.seeding import seed_station

    eng = create_engine(f"sqlite:///{tmp_path}/test.db")
    Base.metadata.create_all(eng)
    Session = sessionmaker(bind=eng)
    db = Session()
    try:
        import_source(
            db, STATEFUL_CONTENT_XML, "STATEFUL_CONTENT", role="content",
        )
        seed_station(db, STATEFUL_JSON)
        db.commit()

        pids = generate_chain(
            db, station_slug="stateful-starter",
            weeks=[1, 2], seed_base=42,
        )
        assert len(pids[1]) == 336
        assert len(pids[2]) == 336
        # Cursor advanced — same template position, different track.
        assert pids[1][0] != pids[2][0], (
            "persistent cursor did not advance between weeks 1 and 2"
        )
    finally:
        db.close()


def test_end_to_end_generate_14_weeks_wraps_cursor(tmp_path) -> None:
    """The 24/14 cycle math: after 14 weeks the cursor returns to its
    starting position. Week 1 slot 0 == week 15 slot 0 (or whatever
    the actual cycle wrap looks like — pin via the engine's behaviour
    rather than my expectation of it).

    Marked separately from the two-week test because generating 14
    weeks is slow (~5s). Pin the cycle behaviour without paying that
    cost on every fast-loop test run."""
    from sqlalchemy import create_engine
    from sqlalchemy.orm import sessionmaker

    from engine.importer import import_source
    from engine.models import Base
    from engine.persistence import generate_chain
    from engine.seeding import seed_station

    eng = create_engine(f"sqlite:///{tmp_path}/cycle.db")
    Base.metadata.create_all(eng)
    Session = sessionmaker(bind=eng)
    db = Session()
    try:
        import_source(
            db, STATEFUL_CONTENT_XML, "STATEFUL_CONTENT", role="content",
        )
        seed_station(db, STATEFUL_JSON)
        db.commit()

        # 15 weeks: weeks 1-14 fill one cycle; week 15 should map
        # back to where week 1 sat.
        pids = generate_chain(
            db, station_slug="stateful-starter",
            weeks=list(range(1, 16)),
            seed_base=42,
        )
        # All weeks produced 336 picks.
        for w in range(1, 16):
            assert len(pids[w]) == 336, f"week {w} produced {len(pids[w])}"
        # The cycle wrap: week 1 slot 0 = week 15 slot 0 (cursor at
        # position 0 again after 14 advances of 24).
        assert pids[1][0] == pids[15][0], (
            "cursor cycle didn't wrap as expected — week 15 slot 0 "
            "should equal week 1 slot 0 after 14×24=336 advances "
            f"(pool size). Got {pids[1][0]} vs {pids[15][0]}."
        )
    finally:
        db.close()
