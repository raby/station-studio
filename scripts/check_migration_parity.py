"""Structural parity check between `alembic upgrade head` and `Base.metadata.create_all`.

Catches the "added a model class but forgot to alembic-revision" regression
class (DESIGN.md §17 review S2). Both paths are supposed to produce the same
schema from the same source of truth (engine/models.py); this script proves
that holds at HEAD by running both against fresh empty SQLite files and
comparing structurally via SQLAlchemy's Inspector.

Why structural and not text-diff: Alembic's autogenerated CREATE TABLE
statements order constraints differently from SQLAlchemy's create_all
(PK → FK → UNIQUE vs PK → UNIQUE → FK). The two are semantically
identical; text-diff treats them as drift. PRAGMA-level inspection
normalises by extracting columns / pk / FKs / uniques / indexes as
sorted tuples — order of declaration irrelevant.

Wired via `make migration-parity` and CI; exits 1 on drift, 0 on parity.
"""
from __future__ import annotations

import os
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

from sqlalchemy import create_engine, inspect
from sqlalchemy.engine import Engine

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from engine.models import Base  # noqa: E402


def schema_snapshot(engine: Engine) -> dict[str, dict[str, Any]]:
    """Return a normalised schema dict for the engine's DB.

    Each table maps to {columns, pk, fks, uniques, indexes}, all
    sorted so declaration order doesn't matter for the diff.
    """
    insp = inspect(engine)
    out: dict[str, dict[str, Any]] = {}
    for tname in sorted(insp.get_table_names()):
        if tname == "alembic_version":
            # Alembic's own tracking table; expected to differ between
            # the two snapshots (only alembic creates it).
            continue
        out[tname] = {
            "columns": sorted(
                (c["name"], str(c["type"]), c["nullable"])
                for c in insp.get_columns(tname)
            ),
            "pk": sorted(insp.get_pk_constraint(tname)["constrained_columns"]),
            "fks": sorted(
                (
                    tuple(fk["constrained_columns"]),
                    fk["referred_table"],
                    tuple(fk["referred_columns"]),
                    (fk.get("options") or {}).get("ondelete"),
                )
                for fk in insp.get_foreign_keys(tname)
            ),
            "uniques": sorted(
                tuple(sorted(uc["column_names"]))
                for uc in insp.get_unique_constraints(tname)
            ),
            "indexes": sorted(
                (tuple(idx["column_names"]), bool(idx.get("unique")))
                for idx in insp.get_indexes(tname)
            ),
        }
    return out


def diff_schemas(left: dict, right: dict, left_name: str, right_name: str) -> list[str]:
    """Return a human-readable list of differences. Empty list = identical."""
    diffs: list[str] = []
    only_left = sorted(set(left) - set(right))
    only_right = sorted(set(right) - set(left))
    for t in only_left:
        diffs.append(f"  Table {t!r} exists in {left_name} but not {right_name}")
    for t in only_right:
        diffs.append(f"  Table {t!r} exists in {right_name} but not {left_name}")

    common = sorted(set(left) & set(right))
    for t in common:
        for key in ("columns", "pk", "fks", "uniques", "indexes"):
            if left[t][key] != right[t][key]:
                diffs.append(
                    f"  Table {t!r}, {key}:\n"
                    f"    {left_name}:  {left[t][key]}\n"
                    f"    {right_name}: {right[t][key]}"
                )
    return diffs


def main() -> int:
    with tempfile.TemporaryDirectory() as tmpdir:
        alembic_path = Path(tmpdir) / "alembic.db"
        createall_path = Path(tmpdir) / "createall.db"

        # Run alembic upgrade head against an empty DB.
        env = {**os.environ, "STATION_STUDIO_DB_URL": f"sqlite:///{alembic_path}"}
        result = subprocess.run(
            [str(REPO_ROOT / ".venv" / "bin" / "alembic"), "upgrade", "head"],
            env=env,
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            print("alembic upgrade head failed:", file=sys.stderr)
            print(result.stderr, file=sys.stderr)
            return 1

        # Run create_all against another empty DB.
        Base.metadata.create_all(create_engine(f"sqlite:///{createall_path}"))

        a_schema = schema_snapshot(create_engine(f"sqlite:///{alembic_path}"))
        c_schema = schema_snapshot(create_engine(f"sqlite:///{createall_path}"))

        diffs = diff_schemas(a_schema, c_schema, "alembic", "create_all")
        if not diffs:
            print(
                f"✓ migration parity: alembic upgrade head matches create_all "
                f"({len(a_schema)} tables)"
            )
            return 0

        print("✗ schema drift between alembic and create_all:")
        for d in diffs:
            print(d)
        print()
        print(
            "Hint: run 'make alembic-revision msg=\"…\"' against a DB that's at "
            "the OLD schema to autogenerate a migration capturing the delta."
        )
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
